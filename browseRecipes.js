function displayRecipes() {
    if (!recipeContainer) return;

    const searchText = searchInput.value.toLowerCase();
    const category = categoryFilter.value;
    const difficulty = difficultyFilter.value;

    const filtered = window.recipes.filter(recipe => {
        const matchesSearch =
            recipe.name.toLowerCase().includes(searchText) ||
            recipe.categoryName.toLowerCase().includes(searchText) ||
            recipe.ingredients.some(i => i.toLowerCase().includes(searchText));
        const matchesCategory = category === "all" || recipe.category === category;
        const matchesDifficulty = difficulty === "all" || recipe.difficulty === difficulty;
        return matchesSearch && matchesCategory && matchesDifficulty;
    });

    recipeContainer.innerHTML = "";
    recipeCount.textContent =
        filtered.length + " drink" + (filtered.length === 1 ? "" : "s") + " found";
    noResults.hidden = filtered.length > 0;

    filtered.forEach(recipe => {
        const card = document.createElement("div");
        card.className = "recipe-card";
        card.tabIndex = 0;
        card.setAttribute("role", "button");
        card.setAttribute("aria-label", "View " + recipe.name);

        card.innerHTML = `
            <img src="${recipe.image}" alt="${recipe.name}">
            <h3>${recipe.name}</h3>
            <p>${recipe.categoryName}</p>
            <p>Preparation time: ${recipe.preparationTime}</p>
            <p>Difficulty: ${recipe.difficulty}</p>
        `;

        function openRecipe() {
            window.location.href = "recipeDetails.html?id=" + recipe.id;
        }

        card.addEventListener("click", openRecipe);
        card.addEventListener("keydown", function (event) {
            if (event.key === "Enter" || event.key === " ") {
                event.preventDefault();
                openRecipe();
            }
        });

        recipeContainer.appendChild(card);
    });
}

["input", "change"].forEach(function (eventName) {
    searchInput.addEventListener(eventName, displayRecipes);
    categoryFilter.addEventListener(eventName, displayRecipes);
    difficultyFilter.addEventListener(eventName, displayRecipes);
});

resetFilters.addEventListener("click", function () {
    searchInput.value = "";
    categoryFilter.value = "all";
    difficultyFilter.value = "all";
    displayRecipes();
});

displayRecipes();

